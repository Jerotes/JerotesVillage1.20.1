	@Override
	public boolean doHurtTarget(Entity entity) {
		if (entity instanceof LivingEntity livingEntity && this.getRandom().nextFloat() < 0.2) {
			if (!this.level().isClientSide()) {
				this.setAnimTick(11);
				this.setAnimationState("stab");
			}
			boolean bl;
			DamageSource damageSource = AttackFind.findDamageType(livingEntity, JerotesDamageTypes.POISON, this);
			AttackFind.attackBegin(this, livingEntity);
			bl = AttackFind.attackAfterCustomDamage(this, livingEntity, damageSource,0.75f, 0f, false, 0f);
			if (bl) {
				if (!this.isSilent()) {
					this.playSound(JerotesVillageSoundEvents.PURPLE_SAND_SCORPION_STAB, 1.0f, 1.0f);
				}
				if (!this.level().isClientSide) {
					livingEntity.addEffect(new MobEffectInstance(JerotesMobEffects.DEADLY_POISON.get(), 120, 1), this);
				}
			}
			else {
				AttackFind.attackBegin(this, livingEntity);
				bl = AttackFind.attackAfter(this, livingEntity, 0.75f, 0.2f, false, 0f);
				if (bl) {
					if (!this.isSilent()) {
						this.playSound(JerotesVillageSoundEvents.PURPLE_SAND_SCORPION_STAB, 1.0f, 1.0f);
					}
				}
			}
			return bl;
		}
		else {
			if (!this.level().isClientSide()) {
				int attackRandom = this.getRandom().nextInt(30);
				if (attackRandom < 10) {
					this.setAnimTick(9);
					this.setAnimationState("attack1");
				}
				else if (attackRandom < 20) {
					this.setAnimTick(9);
					this.setAnimationState("attack2");
				}
				else {
					this.setAnimTick(10);
					this.setAnimationState("attack3");
				}
			}
			boolean bl = super.doHurtTarget(entity);
			if (bl) {
				if (!this.isSilent()) {
					this.playSound(JerotesVillageSoundEvents.PURPLE_SAND_SCORPION_ATTACK, 1.0f, 1.0f);
				}
			}
			return bl;
		}
	}

